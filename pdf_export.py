import re
from io import BytesIO
from pathlib import Path

from fpdf import FPDF

FONT_REGULAR = [
    Path(r"C:\Windows\Fonts\arial.ttf"),
    Path(r"C:\Windows\Fonts\calibri.ttf"),
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    Path("/Library/Fonts/Arial.ttf"),
]
FONT_BOLD = [
    Path(r"C:\Windows\Fonts\arialbd.ttf"),
    Path(r"C:\Windows\Fonts\calibrib.ttf"),
    Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    Path("/Library/Fonts/Arial Bold.ttf"),
]


def _first_existing(paths):
    for path in paths:
        if path.exists():
            return str(path)
    return None


def _clean(text: str) -> str:
    text = str(text or "")
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[*_`#]+", "", text)
    return text.replace("\u00a0", " ").strip()


class ReportPDF(FPDF):
    def header(self):
        self.set_font("Report", "B", 9)
        self.set_text_color(255, 140, 50)
        self.cell(0, 8, "ResearchMind  ·  Research Report", align="L")
        self.set_draw_color(255, 140, 50)
        self.set_line_width(0.3)
        self.line(10, 16, 200, 16)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font("Report", size=8)
        self.set_text_color(120, 118, 112)
        self.cell(0, 10, f"Page {self.page_no()}  |  Generated by ResearchMind", align="C")


def build_report_pdf(topic: str, report: str, feedback: str | None = None) -> bytes:
    regular = _first_existing(FONT_REGULAR)
    bold = _first_existing(FONT_BOLD) or regular

    pdf = ReportPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(16, 20, 16)

    if regular:
        pdf.add_font("Report", "", regular)
        pdf.add_font("Report", "B", bold)
        font_name = "Report"
    else:
        font_name = "Helvetica"

    pdf.add_page()
    pdf.set_font(font_name, "B", 18)
    pdf.set_text_color(20, 20, 24)
    pdf.multi_cell(0, 9, _clean(topic) or "Research Report")
    pdf.ln(3)

    pdf.set_font(font_name, "", 11)
    pdf.set_text_color(40, 38, 36)
    _write_markdown(pdf, font_name, report)

    if feedback:
        pdf.add_page()
        pdf.set_font(font_name, "B", 16)
        pdf.set_text_color(40, 140, 80)
        pdf.cell(0, 10, "Critic Feedback", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)
        pdf.set_font(font_name, "", 11)
        pdf.set_text_color(40, 38, 36)
        _write_markdown(pdf, font_name, feedback)

    return bytes(pdf.output())


def _write_markdown(pdf: FPDF, font_name: str, text: str) -> None:
    for raw in str(text or "").splitlines():
        line = raw.rstrip()
        if not line.strip():
            pdf.ln(3)
            continue

        heading = re.match(r"^(#{1,3})\s+(.*)$", line)
        bullet = re.match(r"^[-*]\s+(.*)$", line)

        if heading:
            level = len(heading.group(1))
            size = {1: 15, 2: 13, 3: 12}[level]
            pdf.ln(2)
            pdf.set_font(font_name, "B", size)
            pdf.set_text_color(24, 24, 28)
            pdf.multi_cell(0, 8, _clean(heading.group(2)))
            pdf.set_font(font_name, "", 11)
            pdf.set_text_color(40, 38, 36)
            continue

        if bullet:
            pdf.set_x(pdf.l_margin + 4)
            pdf.multi_cell(0, 6.5, f"• {_clean(bullet.group(1))}")
            continue

        pdf.multi_cell(0, 6.5, _clean(line))
