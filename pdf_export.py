def _first_existing(paths):
    for path in paths:
        if path.exists():
            return str(path)
    return None


def _clean_text(text: str, is_unicode_font: bool = True) -> str:
    text = str(text or "")
    # Format markdown links [Text](URL) -> Text (URL)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r"\1 (\2)", text)
    # Strip markdown styling asterisks, underscores, backticks, hashes
    text = re.sub(r"[*_`]+", "", text)
    text = text.replace("\u00a0", " ")

    if not is_unicode_font:
        replacements = {
            "\u201c": '"',
            "\u201d": '"',
            "\u2018": "'",
            "\u2019": "'",
            "\u2014": "-",
            "\u2013": "-",
            "\u2022": "-",
            "\u2026": "...",
            "\u00b7": "-",
        }
        for k, v in replacements.items():
            text = text.replace(k, v)
        text = text.encode("latin-1", "replace").decode("latin-1")

    return text.strip()


class ReportPDF(FPDF):
    def __init__(self, font_family="Helvetica", *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.font_family_name = font_family

    def header(self):
        self.set_font(self.font_family_name, "B", 8)
        self.set_text_color(255, 140, 50)
        self.cell(0, 6, "ResearchMind  ·  AI Research Report", align="L", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(255, 140, 50)
        self.set_line_width(0.3)
        self.line(self.l_margin, 14, self.w - self.r_margin, 14)
        self.ln(6)

    def footer(self):
        self.set_y(-14)
        self.set_font(self.font_family_name, size=8)
        self.set_text_color(130, 126, 120)
        self.cell(0, 8, f"Page {self.page_no()}  |  Generated by ResearchMind Multi-Agent System", align="C")


def build_report_pdf(topic: str, report: str, feedback: str | None = None) -> bytes:
    regular = _first_existing(FONT_REGULAR)
    bold = _first_existing(FONT_BOLD) or regular

    font_name = "Report" if regular else "Helvetica"
    is_unicode = regular is not None

    pdf = ReportPDF(font_family=font_name, format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(16, 18, 16)

    if regular:
        pdf.add_font("Report", "", regular)
        pdf.add_font("Report", "B", bold)

    pdf.add_page()

    # Topic Title
    pdf.set_font(font_name, "B", 18)
    pdf.set_text_color(24, 24, 28)
    clean_topic = _clean_text(topic, is_unicode) or "Research Report"
    pdf.multi_cell(0, 9, clean_topic, new_x="LMARGIN", new_y="NEXT")

    # Subtitle / Metadata timestamp
    pdf.ln(1)
    pdf.set_font(font_name, "", 9)
    pdf.set_text_color(120, 115, 110)
    timestamp = datetime.now().strftime("%B %d, %Y · %H:%M")
    pdf.cell(0, 5, f"Generated on {timestamp}  |  ResearchMind Multi-Agent System", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    # Accent divider under title
    pdf.set_draw_color(230, 225, 220)
    pdf.set_line_width(0.2)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(4)

    # Main Report Body
    pdf.set_font(font_name, "", 10.5)
    pdf.set_text_color(40, 38, 36)
    _write_markdown(pdf, font_name, report, is_unicode)

    # Critic Feedback Section (if provided)
    if feedback and str(feedback).strip():
        pdf.ln(4)
        pdf.set_draw_color(80, 200, 120)
        pdf.set_line_width(0.4)
        pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
        pdf.ln(4)

        pdf.set_font(font_name, "B", 13)
        pdf.set_text_color(40, 150, 80)
        pdf.cell(0, 8, "Critic Review & Quality Assessment", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

        pdf.set_font(font_name, "", 10)
        pdf.set_text_color(45, 43, 40)
        _write_markdown(pdf, font_name, feedback, is_unicode)

    return bytes(pdf.output())


def _write_markdown(pdf: FPDF, font_name: str, text: str, is_unicode: bool = True) -> None:
    bullet_char = "•" if is_unicode else "-"
    for raw in str(text or "").splitlines():
        line = raw.rstrip()
        if not line.strip():
            pdf.ln(2.5)
            continue

        heading = re.match(r"^(#{1,4})\s+(.*)$", line)
        bullet = re.match(r"^[-*]\s+(.*)$", line)
        numbered = re.match(r"^(\d+[\.\)])\s+(.*)$", line)

        if heading:
            level = len(heading.group(1))
            size = {1: 14, 2: 12.5, 3: 11.5, 4: 10.5}.get(level, 11)
            pdf.ln(2.5)
            pdf.set_font(font_name, "B", size)
            pdf.set_text_color(24, 24, 28)
            pdf.multi_cell(0, 7.5, _clean_text(heading.group(2), is_unicode), new_x="LMARGIN", new_y="NEXT")
            pdf.set_font(font_name, "", 10.5)
            pdf.set_text_color(40, 38, 36)
            continue

        if bullet:
            pdf.set_x(pdf.l_margin + 4)
            pdf.multi_cell(
                pdf.epw - 4,
                6.0,
                f"{bullet_char}  {_clean_text(bullet.group(1), is_unicode)}",
                new_x="LMARGIN",
                new_y="NEXT",
            )
            continue

        if numbered:
            num_tag = numbered.group(1)
            pdf.set_x(pdf.l_margin + 4)
            pdf.multi_cell(
                pdf.epw - 4,
                6.0,
                f"{num_tag} {_clean_text(numbered.group(2), is_unicode)}",
                new_x="LMARGIN",
                new_y="NEXT",
            )
            continue

        pdf.multi_cell(0, 6.0, _clean_text(line, is_unicode), new_x="LMARGIN", new_y="NEXT")
